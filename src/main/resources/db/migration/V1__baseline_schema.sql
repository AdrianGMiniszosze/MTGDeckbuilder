COMMENT ON TABLE users            IS 'Application users; passwords stored as BCrypt hashes.';
COMMENT ON TABLE sets             IS 'MTG sets, keyed by Scryfall set code when available.';
COMMENT ON TABLE cards            IS 'Card printings. scryfall_id is the unique printing identity; oracle_id groups reprints.';
COMMENT ON TABLE formats          IS 'Format structural rules; card legality lives in card_legality.';
COMMENT ON TABLE card_legality    IS 'Per card printing and format legality from Scryfall.';
COMMENT ON TABLE decks            IS 'User-created decks. Sections live in card_deck.';
COMMENT ON TABLE card_deck        IS 'Deck composition: card, quantity and section (main/sideboard/maybeboard).';
COMMENT ON TABLE card_tag         IS 'Card tags with confidence and provenance metadata.';
COMMENT ON COLUMN decks.is_private IS 'When true the deck is only visible to its owner.';
COMMENT ON COLUMN formats.max_copies IS 'Maximum copies of a non-exempt card; 1 for singleton formats.';
