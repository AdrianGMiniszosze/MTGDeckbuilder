-- ============================================================================
-- V1 — Baseline schema (consolidated)
-- ----------------------------------------------------------------------------
-- Single source of truth for the database schema.
--
-- This migration consolidates the former bootstrap scripts and migrations
-- V2–V5 into one baseline. The project has no deployed environments, so the
-- local database may be recreated from scratch.
--
-- From this point on, migrations are immutable: fix forward with a new V* file,
-- never edit an already-applied migration.
--
-- Design: docs/SCHEMA_DESIGN.md
-- ============================================================================

CREATE EXTENSION IF NOT EXISTS vector;

-- ----------------------------------------------------------------------------
-- users
-- ----------------------------------------------------------------------------
CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            TEXT NOT NULL,
    username        TEXT NOT NULL UNIQUE,
    email           TEXT NOT NULL UNIQUE,
    hashed_password TEXT NOT NULL,
    country         TEXT,
    role            TEXT NOT NULL DEFAULT 'USER' CHECK (role IN ('USER', 'ADMIN')),
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    last_login      TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ----------------------------------------------------------------------------
-- sets
-- ----------------------------------------------------------------------------
CREATE TABLE sets (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT NOT NULL UNIQUE,
    code        TEXT UNIQUE,
    released_at DATE,
    set_type    TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ----------------------------------------------------------------------------
-- cards
-- ----------------------------------------------------------------------------
-- scryfall_id is the unique printing identity. oracle_id identifies the card
-- across reprints and is intentionally NOT unique.
-- `embedding` is deferred to V3__add_card_embeddings.sql (model/dimension TBD).
CREATE TABLE cards (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scryfall_id       UUID UNIQUE,
    oracle_id         UUID,
    card_name         TEXT NOT NULL,
    mana_cost         TEXT,
    cmc               INTEGER NOT NULL,
    color_identity    TEXT,
    type_line         TEXT NOT NULL,
    card_type         TEXT NOT NULL,
    card_supertype    TEXT,
    rarity            TEXT NOT NULL,
    card_text         TEXT NOT NULL DEFAULT '',
    flavor_text       TEXT,
    power             TEXT,
    toughness         TEXT,
    unlimited_copies  BOOLEAN NOT NULL DEFAULT FALSE,
    is_basic_land     BOOLEAN NOT NULL DEFAULT FALSE,
    image_url         TEXT NOT NULL,
    foil              BOOLEAN NOT NULL DEFAULT FALSE,
    game_changer      BOOLEAN NOT NULL DEFAULT FALSE,
    related_card_id   BIGINT REFERENCES cards(id) ON DELETE SET NULL,
    parent_card_id    BIGINT REFERENCES cards(id) ON DELETE SET NULL,
    language          TEXT NOT NULL DEFAULT 'en',
    archetype         TEXT,
    set_id            BIGINT REFERENCES sets(id) ON DELETE SET NULL,
    collector_number  TEXT NOT NULL DEFAULT 'unknown',
    promo             BOOLEAN NOT NULL DEFAULT FALSE,
    variation         BOOLEAN NOT NULL DEFAULT FALSE,
    usd               NUMERIC(12, 4) CHECK (usd IS NULL OR usd >= 0),
    usd_foil          NUMERIC(12, 4) CHECK (usd_foil IS NULL OR usd_foil >= 0),
    usd_etched        NUMERIC(12, 4) CHECK (usd_etched IS NULL OR usd_etched >= 0),
    eur               NUMERIC(12, 4) CHECK (eur IS NULL OR eur >= 0),
    eur_foil          NUMERIC(12, 4) CHECK (eur_foil IS NULL OR eur_foil >= 0),
    eur_etched        NUMERIC(12, 4) CHECK (eur_etched IS NULL OR eur_etched >= 0),
    tix               NUMERIC(12, 4) CHECK (tix IS NULL OR tix >= 0),
    price_observed_at TIMESTAMPTZ,
    imported_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ----------------------------------------------------------------------------
-- Card attribute tables
-- ----------------------------------------------------------------------------
-- No closed CHECK lists on types/supertypes: Scryfall may add new values and
-- ingestion must not fail because of them.
CREATE TABLE card_colors (
    card_id BIGINT NOT NULL REFERENCES cards(id) ON DELETE CASCADE,
    color   CHAR(1) NOT NULL CHECK (color IN ('W', 'U', 'B', 'R', 'G')),
    PRIMARY KEY (card_id, color)
);

CREATE TABLE card_color_identity (
    card_id BIGINT NOT NULL REFERENCES cards(id) ON DELETE CASCADE,
    color   CHAR(1) NOT NULL CHECK (color IN ('W', 'U', 'B', 'R', 'G')),
    PRIMARY KEY (card_id, color)
);

CREATE TABLE card_types (
    card_id BIGINT NOT NULL REFERENCES cards(id) ON DELETE CASCADE,
    type    TEXT NOT NULL,
    PRIMARY KEY (card_id, type)
);

CREATE TABLE card_supertypes (
    card_id   BIGINT NOT NULL REFERENCES cards(id) ON DELETE CASCADE,
    supertype TEXT NOT NULL,
    PRIMARY KEY (card_id, supertype)
);

CREATE TABLE card_subtypes (
    card_id BIGINT NOT NULL REFERENCES cards(id) ON DELETE CASCADE,
    subtype TEXT NOT NULL,
    PRIMARY KEY (card_id, subtype)
);

CREATE TABLE card_keywords (
    card_id BIGINT NOT NULL REFERENCES cards(id) ON DELETE CASCADE,
    keyword TEXT NOT NULL,
    PRIMARY KEY (card_id, keyword)
);

-- ----------------------------------------------------------------------------
-- card_faces
-- ----------------------------------------------------------------------------
CREATE TABLE card_faces (
    card_id         BIGINT NOT NULL REFERENCES cards(id) ON DELETE CASCADE,
    face_index      SMALLINT NOT NULL CHECK (face_index >= 0),
    name            TEXT NOT NULL,
    mana_cost       TEXT NOT NULL DEFAULT '',
    type_line       TEXT,
    oracle_text     TEXT,
    colors          JSONB,
    color_indicator JSONB,
    power           TEXT,
    toughness       TEXT,
    loyalty         TEXT,
    defense         TEXT,
    image_uris      JSONB,
    face_data       JSONB NOT NULL CHECK (jsonb_typeof(face_data) = 'object'),
    PRIMARY KEY (card_id, face_index)
);

-- ----------------------------------------------------------------------------
-- card_rulings (keyed by oracle identity, shared across printings)
-- ----------------------------------------------------------------------------
CREATE TABLE card_rulings (
    oracle_id    UUID NOT NULL,
    published_at DATE NOT NULL,
    comment      TEXT NOT NULL,
    source       TEXT NOT NULL,
    PRIMARY KEY (oracle_id, published_at, comment, source)
);

-- ----------------------------------------------------------------------------
-- formats
-- ----------------------------------------------------------------------------
-- Structural rules only. Card legality lives exclusively in card_legality.
-- max_deck_size NULL          = no upper bound
-- max_sideboard_size NULL     = no upper bound
-- singleton                   = at most one copy of any non-exempt card
-- requires_commander          = deck must designate a commander
CREATE TABLE formats (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    format_name        TEXT NOT NULL UNIQUE,
    description        TEXT,
    min_deck_size      INTEGER NOT NULL DEFAULT 60 CHECK (min_deck_size >= 0),
    max_deck_size      INTEGER CHECK (max_deck_size IS NULL OR max_deck_size >= min_deck_size),
    max_sideboard_size INTEGER CHECK (max_sideboard_size IS NULL OR max_sideboard_size >= 0),
    max_copies         INTEGER NOT NULL DEFAULT 4 CHECK (max_copies >= 1),
    singleton          BOOLEAN NOT NULL DEFAULT FALSE,
    requires_commander BOOLEAN NOT NULL DEFAULT FALSE,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ----------------------------------------------------------------------------
-- card_legality
-- ----------------------------------------------------------------------------
CREATE TABLE card_legality (
    card_id         BIGINT NOT NULL REFERENCES cards(id) ON DELETE CASCADE,
    format_id       BIGINT NOT NULL REFERENCES formats(id) ON DELETE CASCADE,
    legality_status TEXT NOT NULL
        CHECK (legality_status IN ('legal', 'not_legal', 'restricted', 'banned')),
    PRIMARY KEY (card_id, format_id)
);

-- ----------------------------------------------------------------------------
-- decks
-- ----------------------------------------------------------------------------
-- Section (main/sideboard/maybeboard) belongs to card_deck, not to the deck.
CREATE TABLE decks (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    deck_name         TEXT NOT NULL,
    description       TEXT,
    format_id         BIGINT NOT NULL REFERENCES formats(id),
    user_id           BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    is_private        BOOLEAN NOT NULL DEFAULT TRUE,
    tournament        TEXT,
    share_url         TEXT UNIQUE,
    parent_deck_id    BIGINT REFERENCES decks(id) ON DELETE SET NULL,
    companion_card_id BIGINT REFERENCES cards(id) ON DELETE SET NULL,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ----------------------------------------------------------------------------
-- card_deck
-- ----------------------------------------------------------------------------
CREATE TABLE card_deck (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    deck_id  BIGINT NOT NULL REFERENCES decks(id) ON DELETE CASCADE,
    card_id  BIGINT NOT NULL REFERENCES cards(id) ON DELETE CASCADE,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    section  TEXT NOT NULL DEFAULT 'main' CHECK (section IN ('main', 'sideboard', 'maybeboard')),
    UNIQUE (deck_id, card_id, section)
);

-- ----------------------------------------------------------------------------
-- tags / card_tag
-- ----------------------------------------------------------------------------
CREATE TABLE tags (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE
);

CREATE TABLE card_tag (
    card_id       BIGINT NOT NULL REFERENCES cards(id) ON DELETE CASCADE,
    tag_id        BIGINT NOT NULL REFERENCES tags(id) ON DELETE CASCADE,
    weight        DOUBLE PRECISION NOT NULL CHECK (weight >= 0),
    confidence    DOUBLE PRECISION NOT NULL DEFAULT 1.0 CHECK (confidence BETWEEN 0 AND 1),
    source        TEXT NOT NULL DEFAULT 'manual',
    model_version TEXT,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (card_id, tag_id)
);

-- ----------------------------------------------------------------------------
-- card_relationships
-- ----------------------------------------------------------------------------
CREATE TABLE card_relationships (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_card_id    BIGINT NOT NULL REFERENCES cards(id) ON DELETE CASCADE,
    related_card_id   BIGINT NOT NULL REFERENCES cards(id) ON DELETE CASCADE,
    relationship_type TEXT NOT NULL,
    face_order        INTEGER,
    UNIQUE (parent_card_id, related_card_id, relationship_type)
);

