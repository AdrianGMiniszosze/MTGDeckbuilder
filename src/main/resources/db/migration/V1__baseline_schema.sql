-- ----------------------------------------------------------------------------
-- updated_at maintenance
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_users_updated_at
    BEFORE UPDATE ON users
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_sets_updated_at
    BEFORE UPDATE ON sets
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_cards_updated_at
    BEFORE UPDATE ON cards
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_formats_updated_at
    BEFORE UPDATE ON formats
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_decks_updated_at
    BEFORE UPDATE ON decks
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ----------------------------------------------------------------------------
-- Deck integrity trigger (second line of defence after DeckValidationService)
-- ----------------------------------------------------------------------------
-- Rules enforced here:
--   * quantity > 0 and a valid section (also covered by CHECK constraints)
--   * card and deck must exist
--   * banned / not_legal cards are rejected
--   * copy limit = 1 when restricted or singleton, else format max_copies
--   * basic lands and unlimited_copies cards are exempt from copy limits
--   * copies are summed across main + sideboard (maybeboard is exempt)
--   * max_sideboard_size and max_deck_size are enforced when not NULL
--   * decks.updated_at is refreshed on every card change
--
-- Minimum deck size cannot be enforced per row: DeckValidationService checks it
-- when the deck is finalized.
CREATE OR REPLACE FUNCTION check_card_quantity()
RETURNS TRIGGER AS $$
DECLARE
    deck_format_id           BIGINT;
    format_name_value        TEXT;
    legality                 TEXT;
    card_is_basic_land       BOOLEAN;
    card_unlimited_copies    BOOLEAN;
    format_max_copies        INTEGER;
    format_singleton         BOOLEAN;
    format_max_sideboard     INTEGER;
    format_max_deck          INTEGER;
    allowed_copies           INTEGER;
    copies_other_sections    INTEGER;
    section_total            INTEGER;
BEGIN
    IF NEW.quantity IS NULL OR NEW.quantity <= 0 THEN
        RAISE EXCEPTION 'Quantity must be greater than zero (card_id=%)', NEW.card_id
            USING ERRCODE = 'check_violation';
    END IF;

    IF NEW.section IS NULL OR NEW.section NOT IN ('main', 'sideboard', 'maybeboard') THEN
        RAISE EXCEPTION 'Invalid deck section: %', NEW.section
            USING ERRCODE = 'check_violation';
    END IF;

    -- Keep the deck modification timestamp in sync with its contents.
    UPDATE decks SET updated_at = now() WHERE id = NEW.deck_id;

    -- Maybeboard is a scratch area: no legality or size rules.
    IF NEW.section = 'maybeboard' THEN
        RETURN NEW;
    END IF;

    SELECT d.format_id, f.format_name, f.max_copies, f.singleton,
           f.max_sideboard_size, f.max_deck_size
      INTO deck_format_id, format_name_value, format_max_copies, format_singleton,
           format_max_sideboard, format_max_deck
      FROM decks d
      JOIN formats f ON f.id = d.format_id
     WHERE d.id = NEW.deck_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Deck % does not exist or has no valid format', NEW.deck_id
            USING ERRCODE = 'foreign_key_violation';
    END IF;

    SELECT c.is_basic_land, c.unlimited_copies
      INTO card_is_basic_land, card_unlimited_copies
      FROM cards c
     WHERE c.id = NEW.card_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Card % does not exist', NEW.card_id
            USING ERRCODE = 'foreign_key_violation';
    END IF;

    SELECT cl.legality_status
      INTO legality
      FROM card_legality cl
     WHERE cl.card_id = NEW.card_id
       AND cl.format_id = deck_format_id;

    -- A missing legality row means "unknown yet" (catalogue not fully imported).
    IF legality IN ('banned', 'not_legal') THEN
        RAISE EXCEPTION 'Card % is % in format %', NEW.card_id, legality, format_name_value
            USING ERRCODE = 'check_violation';
    END IF;

    IF card_is_basic_land OR card_unlimited_copies THEN
        allowed_copies := NULL;
    ELSIF legality = 'restricted' OR format_singleton THEN
        allowed_copies := 1;
    ELSE
        allowed_copies := COALESCE(format_max_copies, 4);
    END IF;

    IF allowed_copies IS NOT NULL THEN
        SELECT COALESCE(SUM(cd.quantity) FILTER (WHERE cd.section IS DISTINCT FROM NEW.section), 0)
          INTO copies_other_sections
          FROM card_deck cd
         WHERE cd.deck_id = NEW.deck_id
           AND cd.card_id = NEW.card_id
           AND cd.id IS DISTINCT FROM NEW.id;

        IF copies_other_sections + NEW.quantity > allowed_copies THEN
            RAISE EXCEPTION
                'Card % exceeds the copy limit of % in format % (total would be %)',
                NEW.card_id, allowed_copies, format_name_value,
                copies_other_sections + NEW.quantity
                USING ERRCODE = 'check_violation';
        END IF;
    END IF;

    IF NEW.section = 'sideboard' AND format_max_sideboard IS NOT NULL THEN
        SELECT COALESCE(SUM(cd.quantity), 0)
          INTO section_total
          FROM card_deck cd
         WHERE cd.deck_id = NEW.deck_id
           AND cd.section = 'sideboard'
           AND cd.id IS DISTINCT FROM NEW.id;

        IF section_total + NEW.quantity > format_max_sideboard THEN
            RAISE EXCEPTION
                'Sideboard exceeds the limit of % cards in format %',
                format_max_sideboard, format_name_value
                USING ERRCODE = 'check_violation';
        END IF;
    END IF;

    IF NEW.section = 'main' AND format_max_deck IS NOT NULL THEN
        SELECT COALESCE(SUM(cd.quantity), 0)
          INTO section_total
          FROM card_deck cd
         WHERE cd.deck_id = NEW.deck_id
           AND cd.section = 'main'
           AND cd.id IS DISTINCT FROM NEW.id;

        IF section_total + NEW.quantity > format_max_deck THEN
            RAISE EXCEPTION
                'Main deck exceeds the limit of % cards in format %',
                format_max_deck, format_name_value
                USING ERRCODE = 'check_violation';
        END IF;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER enforce_card_quantity_limit
    BEFORE INSERT OR UPDATE ON card_deck
    FOR EACH ROW
    EXECUTE FUNCTION check_card_quantity();

