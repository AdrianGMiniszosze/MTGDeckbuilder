-- Existing accounts predate email verification and stay usable after upgrade.
ALTER TABLE users
    ADD COLUMN email_verified_at TIMESTAMPTZ;

UPDATE users
SET email_verified_at = COALESCE(created_at, now())
WHERE email_verified_at IS NULL;

COMMENT ON COLUMN users.email_verified_at IS
    'Timestamp when the user proved control of the current email address.';

-- Email verification and password reset secrets are single-use and stored hashed.
CREATE TABLE account_action_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    purpose     VARCHAR(32) NOT NULL
                CHECK (purpose IN ('EMAIL_VERIFICATION', 'PASSWORD_RESET')),
    token_hash  VARCHAR(64) NOT NULL UNIQUE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at  TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ
);

CREATE INDEX idx_account_action_tokens_user_purpose
    ON account_action_tokens(user_id, purpose);
CREATE INDEX idx_account_action_tokens_expires
    ON account_action_tokens(expires_at);

COMMENT ON TABLE account_action_tokens IS
    'Single-use email verification and password reset tokens; only SHA-256 hashes are stored.';
